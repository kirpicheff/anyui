// Package anyui предоставляет лёгкий кроссплатформенный UI-фреймворк на Go
// с программным 2D-рендерингом (без WebView2 и без зависимости от OpenGL/GPU).
//
// Корневой пакет anyui является основной точкой входа для прикладного кода и
// объединяет управление жизненным циклом приложения ([App], [Window]),
// Immediate Mode API интерфейса ([UI]), темы оформления ([Theme]) и
// функциональные опции стилизации ([Option]).
//
// # Модель работы
//
// Фреймворк использует подход Immediate Mode UI: функция отрисовки drawFn
// вызывается при событиях ОС, анимациях или вызове [App.Dispatch]. В простое
// цикл событий ожидает сообщения ОС без нагрузки на CPU.
//
// Все размеры и отступы в виджетах и раскладках задаются в dp (device-independent
// pixels) и автоматически масштабируются под текущий DPI монитора.
//
// # Многопоточность
//
// Вызовы методов [UI] и чтение/изменение состояния интерфейса должны
// выполняться в главном потоке UI (внутри drawFn). Для обновления состояния из
// фоновых горутин используйте [App.Dispatch].
//
// # Архитектура подпакетов
//
//   - [git.gtw.su/kirpich/anyui/ui] — внутренний движок раскладки, фокуса, анимаций и виджетов.
//   - [git.gtw.su/kirpich/anyui/render] — программный 2D-рендерер (BGRA), SDF-примитивы и кеш шрифтов.
//   - [git.gtw.su/kirpich/anyui/platform] — абстракция окна ОС, диалоги, трей и цикл событий.
//
